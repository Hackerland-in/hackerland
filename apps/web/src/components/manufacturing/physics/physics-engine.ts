// ==========================================
// 1. Vector & Mathematical Utilities
// ==========================================

export interface Vector2D {
  x: number;
  y: number;
}

export function vec2(x: number, y: number): Vector2D {
  return { x, y };
}

export function vec2Add(a: Vector2D, b: Vector2D): Vector2D {
  return { x: a.x + b.x, y: a.y + b.y };
}

export function vec2Scale(v: Vector2D, s: number): Vector2D {
  return { x: v.x * s, y: v.y * s };
}

export function vec2Mag(v: Vector2D): number {
  return Math.sqrt(v.x * v.x + v.y * v.y);
}

// ==========================================
// 2. Pacejka Magic Formula Tire Model
// y(x) = D * sin( C * atan( B*x - E*(B*x - atan(B*x)) ) )
// ==========================================

export interface PacejkaParameters {
  B: number; // Stiffness factor
  C: number; // Shape factor (approx 1.3 - 1.65)
  D: number; // Peak value (friction coefficient mu * Fz)
  E: number; // Curvature factor (controls curve drop-off)
}

/**
 * Computes lateral cornering force or longitudinal traction force using Pacejka '89.
 * @param slip Slip angle in radians (lateral) or slip ratio [-1, 1] (longitudinal)
 * @param normalForce Vertical load Fz in Newtons
 * @param frictionCoeff Friction coefficient mu (e.g. 1.2 for race slick, 0.9 for street)
 */
export function calculatePacejkaForce(
  slip: number,
  normalForce: number,
  frictionCoeff: number,
  customParams?: Partial<PacejkaParameters>
): number {
  if (normalForce <= 0) return 0;

  const B = customParams?.B ?? 10.0;
  const C = customParams?.C ?? 1.4;
  const D = (customParams?.D ?? frictionCoeff) * normalForce;
  const E = customParams?.E ?? -0.2;

  const Bx = B * slip;
  const force = D * Math.sin(C * Math.atan(Bx - E * (Bx - Math.atan(Bx))));
  return force;
}

// ==========================================
// 3. Aerodynamics & Atmospheric Modeling
// ==========================================

/**
 * Computes atmospheric air density rho based on altitude (barometric formula).
 * @param altitudeMeters Altitude above sea level in meters
 * @param tempCelsius Ambient temperature in °C
 * @returns Air density in kg/m^3 (approx 1.225 at sea level and 15°C)
 */
export function calculateAirDensity(altitudeMeters: number = 0, tempCelsius: number = 20): number {
  const p0 = 101325; // Sea level standard atmospheric pressure (Pa)
  const T0 = 288.15; // Sea level standard temperature (K)
  const g = 9.80665; // Gravitational acceleration (m/s^2)
  const L = 0.0065;  // Temperature lapse rate (K/m)
  const R = 287.058; // Specific gas constant for dry air (J/(kg*K))

  const tempKelvin = tempCelsius + 273.15;
  const pressure = p0 * Math.pow(1 - (L * altitudeMeters) / T0, (g) / (R * L));
  return pressure / (R * tempKelvin);
}

/**
 * Aerodynamic resistance force opposing velocity: F_drag = 0.5 * rho * CdA * v^2
 * @param velocity Speed relative to air mass (m/s)
 * @param cdA Drag coefficient multiplied by frontal area (m^2)
 * @param airDensity Air density rho (kg/m^3)
 */
export function calculateAeroDrag(velocity: number, cdA: number, airDensity: number = 1.225): number {
  const sign = Math.sign(velocity);
  return 0.5 * airDensity * cdA * (velocity * velocity) * sign;
}

/**
 * Aerodynamic downforce generated by wings/diffusers: F_down = 0.5 * rho * ClA * v^2
 */
export function calculateAeroDownforce(velocity: number, clA: number, airDensity: number = 1.225): number {
  return 0.5 * airDensity * clA * (velocity * velocity);
}

// ==========================================
// 4. Weight / Normal Force Dynamic Load Transfer
// ==========================================

export interface VehicleMassGeometry {
  totalMassKg: number;
  wheelbaseMeters: number;
  staticFrontWeightRatio: number; // e.g. 0.50 for 50/50 balance
  cgHeightMeters: number;          // Center of gravity height above ground
}

export interface DynamicNormalForces {
  frontNormalForceN: number;
  rearNormalForceN: number;
  weightTransferN: number;
  isWheelie: boolean;
  isStoppie: boolean;
}

/**
 * Computes dynamic normal loads on front and rear axles considering longitudinal acceleration.
 * Delta_W = (m * a_x * h_cg) / L
 */
export function calculateLongitudinalLoadTransfer(
  geom: VehicleMassGeometry,
  accelerationMps2: number,
  roadGradientPercent: number = 0,
  gravity: number = 9.80665
): DynamicNormalForces {
  const theta = Math.atan(roadGradientPercent / 100);
  const normalGravityForce = geom.totalMassKg * gravity * Math.cos(theta);

  // Static front/rear load
  const staticFront = normalGravityForce * geom.staticFrontWeightRatio;
  const staticRear = normalGravityForce * (1 - geom.staticFrontWeightRatio);

  // Dynamic transfer: positive acceleration transfers weight to rear; braking transfers to front
  const weightTransfer = (geom.totalMassKg * accelerationMps2 * geom.cgHeightMeters) / geom.wheelbaseMeters;

  let dynamicFront = staticFront - weightTransfer;
  let dynamicRear = staticRear + weightTransfer;

  const isWheelie = dynamicFront <= 0;
  const isStoppie = dynamicRear <= 0;

  if (isWheelie) {
    dynamicFront = 0;
    dynamicRear = normalGravityForce;
  }
  if (isStoppie) {
    dynamicRear = 0;
    dynamicFront = normalGravityForce;
  }

  return {
    frontNormalForceN: Math.max(0, dynamicFront),
    rearNormalForceN: Math.max(0, dynamicRear),
    weightTransferN: weightTransfer,
    isWheelie,
    isStoppie,
  };
}

// ==========================================
// 5. Suspension Mass-Spring-Damper Kinematics
// m * x'' + c * x' + k * x = F_ext
// ==========================================

export interface SuspensionState {
  displacement: number; // meters from rest position (positive = compression)
  velocity: number;     // m/s
}

/**
 * Integrates 1 step of suspension response under external normal load using Symplectic Euler.
 */
export function stepSuspension(
  current: SuspensionState,
  sprungMassKg: number,
  springRateNpm: number,      // N/m (e.g. 35,000 N/m)
  dampingCoeffNsPm: number,   // N*s/m (e.g. 2,500 N*s/m)
  externalForceN: number,
  maxTravelMeters: number = 0.12,
  dt: number = 1 / 60
): SuspensionState {
  if (sprungMassKg <= 0) return current;

  // Restoring spring force: -k * x
  const fSpring = -springRateNpm * current.displacement;
  // Damping force opposing velocity: -c * v
  const fDamper = -dampingCoeffNsPm * current.velocity;

  const netForce = externalForceN + fSpring + fDamper;
  const acceleration = netForce / sprungMassKg;

  // Symplectic Euler
  const newVelocity = current.velocity + acceleration * dt;
  let newDisplacement = current.displacement + newVelocity * dt;

  // Bump stop clamp
  if (Math.abs(newDisplacement) > maxTravelMeters) {
    newDisplacement = Math.sign(newDisplacement) * maxTravelMeters;
  }

  return {
    displacement: newDisplacement,
    velocity: newVelocity,
  };
}

// ==========================================
// 6. Runge-Kutta 4th Order (RK4) Numerical Integrator
// ==========================================

/**
 * Solves y'(t) = f(t, y) with 4th order accuracy.
 */
export function rk4Step(
  y: number,
  derivativeFn: (currentVal: number) => number,
  dt: number
): number {
  const k1 = derivativeFn(y);
  const k2 = derivativeFn(y + 0.5 * dt * k1);
  const k3 = derivativeFn(y + 0.5 * dt * k2);
  const k4 = derivativeFn(y + dt * k3);

  return y + (dt / 6) * (k1 + 2 * k2 + 2 * k3 + k4);
}
